// ── FLATTEN EVENTS ──
function flattenEvents() {
  const events = [];
  const sport = RAW.Wrestling;
  for (const gender of Object.keys(sport)) {
    for (const levelName of Object.keys(sport[gender])) {
      const level = gender === 'boys'
        ? (levelName.includes('JV') ? 'jv' : 'varsity')
        : 'varsity';
      for (const key of Object.keys(sport[gender][levelName])) {
        const d = sport[gender][levelName][key];
        events.push({
          id: key,
          date: d.date,
          time: d.time,
          opponent: d.opponent || '',
          location: d.location || '',
          homeOrAway: d.homeOrAway,
          gender: gender, // 'boys' or 'girls'
          level: level,
          eventType: d.eventType || 'match',
          levelLabel: levelName
        });
      }
    }
  }
  return events;
}

