// ── STATE ──
const MONTHS = [
  { y: 2025, m: 10 }, // November 2025 (month index 10)
  { y: 2025, m: 11 }, // December
  { y: 2026, m: 0  }, // January
  { y: 2026, m: 1  }, // February
  { y: 2026, m: 2  }, // March
];
const MONTH_NAMES = ['January','February','March','April','May','June','July','August','September','October','November','December'];

let currentMonthIdx = 0;
let genderFilter = 'all';
let typeFilter = 'all';
let levelFilter = 'all';

function getFilteredEvents() {
  return ALL_EVENTS.filter(ev => {
    if (genderFilter !== 'all' && ev.gender !== genderFilter) return false;
    if (typeFilter !== 'all' && ev.eventType !== typeFilter) return false;
    if (levelFilter !== 'all' && ev.level !== levelFilter) return false;
    return true;
  });
}

function getEventsForMonth(year, month) {
  const filtered = getFilteredEvents();
  return filtered.filter(ev => {
    const [y, m] = ev.date.split('-').map(Number);
    return y === year && m - 1 === month;
  });
}

function eventsByDate(events) {
  const map = {};
  events.forEach(ev => {
    if (!map[ev.date]) map[ev.date] = [];
    map[ev.date].push(ev);
  });
  return map;
}

function eventClass(ev) {
  if (ev.eventType === 'tournament') return 'tournament';
  return ev.homeOrAway === 'Home' ? 'home' : 'away';
}

function eventLabel(ev) {
  const g = ev.gender === 'boys' ? 'B' : 'G';
  const lvl = ev.level === 'jv' ? ' JV' : '';
  if (ev.eventType === 'tournament') return `${g}${lvl} · ${ev.opponent || 'Tournament'}`;
  return `${g}${lvl} vs ${ev.opponent || 'Opponent'}`;
}

function shortEventLabel(ev) {
  const g = ev.gender === 'boys' ? 'B' : 'G';
  const lvl = ev.level === 'jv' ? 'JV' : 'V';
  return `${g}${lvl}`;
}

function renderCalendar() {
  const { y, m } = MONTHS[currentMonthIdx];
  document.getElementById('monthTitle').textContent = `${MONTH_NAMES[m]} ${y}`;

  const prevBtn = document.getElementById('prevBtn');
  const nextBtn = document.getElementById('nextBtn');
  prevBtn.disabled = currentMonthIdx === 0;
  nextBtn.disabled = currentMonthIdx === MONTHS.length - 1;

  const events = getEventsForMonth(y, m);
  const dateMap = eventsByDate(events);

  const firstDay = new Date(y, m, 1).getDay();
  const daysInMonth = new Date(y, m + 1, 0).getDate();
  const today = new Date();
  const todayStr = `${today.getFullYear()}-${String(today.getMonth()+1).padStart(2,'0')}-${String(today.getDate()).padStart(2,'0')}`;

  let gridHTML = '';

  // Empty cells before first day
  for (let i = 0; i < firstDay; i++) {
    gridHTML += `<div class="cal-cell empty"></div>`;
  }

  // Day cells
  for (let d = 1; d <= daysInMonth; d++) {
    const dateKey = `${y}-${String(m+1).padStart(2,'0')}-${String(d).padStart(2,'0')}`;
    const dayEvents = (dateMap[dateKey] || []).sort((a,b) => (a.time||'').localeCompare(b.time||''));
    const isToday = dateKey === todayStr;
    const maxShow = 3;
    const shown = dayEvents.slice(0, maxShow);
    const moreCount = dayEvents.length - maxShow;

    let eventsHTML = shown.map(ev => {
      const cls = eventClass(ev);
      const typeIcon = ev.eventType === 'tournament' ? '🏆' : '🤼';
      const gLabel = ev.gender === 'boys' ? 'B' : 'G';
      const lvlLabel = ev.level === 'jv' ? 'JV' : 'V';
      const opp = ev.opponent.split(' ').slice(0,2).join(' ');
      return `<div class="cal-event ${cls}" onclick="openEvent('${ev.id.replace(/'/g, "\\'")}')">
        <span class="ev-type-icon">${typeIcon}</span>
        <span class="ev-gender">${gLabel}${lvlLabel}</span>
        <span style="overflow:hidden;text-overflow:ellipsis;">${opp || ev.eventType}</span>
      </div>`;
    }).join('');

    if (moreCount > 0) {
      eventsHTML += `<div class="cal-more" onclick="scrollToList()">+${moreCount} more</div>`;
    }

    gridHTML += `<div class="cal-cell${isToday ? ' today' : ''}${dayEvents.length ? ' has-events' : ''}">
      <span class="cal-day-num">${d}</span>
      <div class="cal-events">${eventsHTML}</div>
    </div>`;
  }

  document.getElementById('calGrid').innerHTML = gridHTML;

  // Render list
  renderList(events);
}

function renderList(events) {
  const listEl = document.getElementById('monthList');
  if (!events.length) {
    listEl.innerHTML = '<div class="cal-empty-month">No events this month</div>';
    return;
  }

  const sorted = [...events].sort((a,b) => {
    if (a.date !== b.date) return a.date.localeCompare(b.date);
    return (a.time||'').localeCompare(b.time||'');
  });

  const monthNames = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

  listEl.innerHTML = sorted.map(ev => {
    const [y, mo, d] = ev.date.split('-').map(Number);
    const cls = eventClass(ev);
    const genderCls = ev.gender === 'boys' ? 'boys' : 'girls';
    const genderLabel = ev.gender === 'boys' ? 'Boys' : 'Girls';
    const lvlLabel = ev.level === 'jv' ? 'JV' : 'Varsity';
    const typeLabel = ev.eventType === 'tournament' ? 'Tournament / Event' : (ev.homeOrAway === 'Home' ? 'Home Match' : 'Away Match');
    const opponentDisplay = ev.opponent || (ev.eventType === 'tournament' ? 'Tournament' : 'Opponent TBA');
    const typeIcon = ev.eventType === 'tournament' ? '🏆' : (ev.homeOrAway === 'Home' ? '🏠' : '✈️');

    return `<div class="list-event-row" onclick="openEvent('${ev.id.replace(/'/g,"\\'")}')">
      <div class="list-date-block">
        <div class="list-date-day">${d}</div>
        <div class="list-date-month">${monthNames[mo-1]}</div>
      </div>
      <div class="list-divider"></div>
      <div class="list-type-badge"><span class="list-badge ${cls}">${typeIcon} ${typeLabel}</span></div>
      <div class="list-info">
        <div class="list-title">${opponentDisplay}</div>
        <div class="list-sub">${lvlLabel} · ${ev.location || 'Location TBA'}</div>
      </div>
      <span class="list-gender-tag ${genderCls}">${genderLabel}</span>
      <div class="list-time">${ev.time || 'TBA'}</div>
    </div>`;
  }).join('');
}

function scrollToList() {
  document.getElementById('monthList').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

// ── NAVIGATION ──
function prevMonth() {
  if (currentMonthIdx > 0) { currentMonthIdx--; renderCalendar(); }
}
function nextMonth() {
  if (currentMonthIdx < MONTHS.length - 1) { currentMonthIdx++; renderCalendar(); }
}

